package com.onda.seaglass.data

import com.onda.seaglass.core.Http
import com.onda.seaglass.core.J
import com.onda.seaglass.core.L10n
import com.onda.seaglass.core.jsonOf
import com.onda.seaglass.core.tr
import okhttp3.MediaType.Companion.toMediaType
import okhttp3.Request
import okhttp3.RequestBody.Companion.toRequestBody
import org.json.JSONObject
import java.time.LocalDate
import java.time.format.DateTimeFormatter
import java.time.format.FormatStyle

/**
 * A song's general data for "Informazioni sul brano", as the iPhone app reads it (SongDetails.swift):
 * YouTube's player data for the video and, for catalogue songs, what the label sent with it, which
 * YouTube writes in the description ("Provided to YouTube by …", the album, ℗, "Released on: …",
 * credits). Anything missing is left out.
 */
data class SongDetails(
    val label: String? = null,
    val copyright: String? = null,
    val album: String? = null,
    /** In the app's language ("7 marzo 2001"). */
    val releaseDate: String? = null,
    val views: Long? = null,
    /** Role in the app's language → names. */
    val credits: List<Pair<String, List<String>>> = emptyList(),
    /** The text of videos without catalogue data. */
    val description: String? = null,
) {
    companion object {
        private const val ENDPOINT = "https://www.youtube.com/youtubei/v1/player?prettyPrint=false"
        private const val VERSION = "20.10.4"

        suspend fun load(videoId: String): SongDetails {
            val body = jsonOf(
                "videoId" to videoId,
                "contentCheckOk" to true,
                "racyCheckOk" to true,
                "context" to jsonOf(
                    "client" to jsonOf(
                        "clientName" to "IOS", "clientVersion" to VERSION, "deviceMake" to "Apple", "deviceModel" to "iPhone16,2",
                        "osName" to "iPhone", "osVersion" to "18.3.2.22D82", "hl" to L10n.locale.language.ifEmpty { "en" },
                    ),
                ),
            )
            val request = Request.Builder().url(ENDPOINT)
                .header("User-Agent", "com.google.ios.youtube/$VERSION (iPhone16,2; U; CPU iOS 18_3_2 like Mac OS X;)")
                .header("X-YouTube-Client-Name", "5")
                .header("X-YouTube-Client-Version", VERSION)
                .post(body.toString().toRequestBody("application/json".toMediaType()))
                .build()
            return parse(JSONObject(Http.text(request)))
        }

        fun parse(json: JSONObject): SongDetails {
            val views = J.string(json, "videoDetails", "viewCount")?.toLongOrNull()
            val text = J.string(json, "videoDetails", "shortDescription").orEmpty()
            return read(text).copy(views = views)
        }

        /** Reads the description YouTube generates for catalogue songs; other descriptions are kept as text. */
        fun read(text: String): SongDetails {
            val lines = text.lines().map { it.trim() }.filter { it.isNotEmpty() }
            val first = lines.firstOrNull()
            if (first == null || !first.startsWith("Provided to YouTube by ")) {
                return SongDetails(description = text.trim().ifEmpty { null })
            }
            var copyright: String? = null
            var album: String? = null
            var released: String? = null
            var sawTitle = false
            val credits = LinkedHashMap<String, MutableList<String>>()
            for (line in lines.drop(1)) {
                when {
                    line.startsWith("℗") || line.startsWith("©") -> if (copyright == null) copyright = line
                    line.startsWith("Released on:") -> released = line.removePrefix("Released on:").trim()
                    line.startsWith("Auto-generated by YouTube") -> Unit
                    !sawTitle && " · " in line -> sawTitle = true
                    sawTitle && album == null && copyright == null && credits.isEmpty() -> album = line
                    ": " in line -> {
                        val role = line.substringBefore(": ").split(Regex("\\s+")).joinToString(" ")
                        val name = line.substringAfter(": ").trim()
                        if (role.isNotEmpty() && role.length <= 40 && name.isNotEmpty()) {
                            val names = credits.getOrPut(role) { mutableListOf() }
                            if (name !in names) names += name
                        }
                    }
                }
            }
            val date = released?.take(10)?.let { runCatching { LocalDate.parse(it) }.getOrNull() }
                ?.format(DateTimeFormatter.ofLocalizedDate(FormatStyle.LONG).withLocale(L10n.locale))
            return SongDetails(
                label = first.removePrefix("Provided to YouTube by "),
                copyright = copyright,
                album = album,
                releaseDate = date,
                credits = credits.map { (role, names) -> roleTitle(role) to names.toList() },
            )
        }

        /** The role in the app's language; combined roles part by part; uncommon ones as YouTube writes them. */
        fun roleTitle(role: String): String =
            translate(role) ?: role.split(", ").joinToString(", ") { translate(it) ?: it }

        private fun translate(role: String): String? = when (role.lowercase()) {
            "composer" -> tr("Compositore")
            "lyricist" -> tr("Autore del testo")
            "composer lyricist", "composer, lyricist", "composer & lyricist" -> tr("Compositore e autore del testo")
            "writer", "author", "songwriter" -> tr("Autore")
            "producer" -> tr("Produttore")
            "co-producer" -> tr("Coproduttore")
            "executive producer" -> tr("Produttore esecutivo")
            "arranger" -> tr("Arrangiatore")
            "mixer", "mixing engineer" -> tr("Missaggio")
            "masterer", "mastering engineer" -> tr("Mastering")
            "recording engineer", "engineer" -> tr("Tecnico del suono")
            "associated performer", "performer" -> tr("Interprete")
            "main artist", "primary artist" -> tr("Artista principale")
            "featured artist" -> tr("Artista ospite")
            "studio personnel" -> tr("Personale di studio")
            "programmer", "programming" -> tr("Programmazione")
            "synthesizer", "synth" -> tr("Sintetizzatore")
            "vocals", "vocalist", "lead vocalist", "background vocalist" -> tr("Voce")
            "guitar", "guitarist" -> tr("Chitarra")
            "bass", "bass guitar", "bassist" -> tr("Basso")
            "drums", "drummer" -> tr("Batteria")
            "keyboards", "keyboard" -> tr("Tastiere")
            "piano", "pianist" -> tr("Pianoforte")
            "unknown" -> tr("Altro")
            else -> null
        }
    }
}
