// Checks how song details are read from YouTube's player data, on descriptions in the shape
// YouTube Music writes for catalogue songs, without the network.
// Run from the repository root: bash Tools/SongDetailsCheck/run.sh
import Foundation

var failures = 0
func expect(_ condition: Bool, _ message: String) {
    print(condition ? "ok   \(message)" : "FAIL \(message)")
    if !condition { failures += 1 }
}

let catalogue = """
Provided to YouTube by Daft Life Ltd./ADA France

One More Time (Radio Edit) · Daft Punk

One More Time

℗ 2001 Daft Life Limited

Released on: 2001-03-07

Drum Machine Drums: Guy-Manuel de Homem-Christo
Producer, Synthesizer: Guy-Manuel de Homem-Christo
Mastering  Engineer: Nilesh Patel
Vocals: Romanthony
Producer, Synthesizer: Thomas Bangalter
Writer: Anthony Moore
Writer: Guy-Manuel de Homem-Christo
Writer: Thomas Bangalter

Auto-generated by YouTube.
"""

let json: [String: Any] = [
    "videoDetails": [
        "author": "Daft Punk - Topic",
        "viewCount": "34618338",
        "lengthSeconds": "321",
        "shortDescription": catalogue,
    ],
    "playerConfig": ["audioConfig": ["loudnessDb": 0.99]],
]
let details = SongDetails(json: json)
expect(details.label == "Daft Life Ltd./ADA France", "label: \(details.label ?? "none")")
expect(details.album == "One More Time", "album: \(details.album ?? "none")")
expect(details.copyright == "℗ 2001 Daft Life Limited", "copyright: \(details.copyright ?? "none")")
expect(details.channel == "Daft Punk", "channel without \" - Topic\": \(details.channel ?? "none")")
expect(details.views == 34_618_338, "plays: \(details.views.map(String.init) ?? "none")")
expect(details.length == 321, "length")
expect(details.loudness == 0.99, "loudness")
expect(details.description == nil, "a catalogue song keeps no description text")

var calendar = Calendar(identifier: .gregorian)
calendar.timeZone = TimeZone(identifier: "UTC")!
let day = details.releaseDate.map { calendar.dateComponents([.year, .month, .day], from: $0) }
expect(day?.year == 2001 && day?.month == 3 && day?.day == 7, "release date: \(String(describing: details.releaseDate))")

let roles = details.credits.map(\.role)
expect(roles == ["Drum Machine Drums", "Producer, Synthesizer", "Mastering Engineer", "Vocals", "Writer"],
       "credit roles in order, merged and with single spaces: \(roles)")
expect(details.credits.first { $0.role == "Writer" }?.names.count == 3, "three writers")
expect(details.credits.first { $0.role == "Producer, Synthesizer" }?.names
           == ["Guy-Manuel de Homem-Christo", "Thomas Bangalter"], "both producers")
let mastering = details.credits.first { $0.role == "Mastering Engineer" }
expect(mastering?.title != "Mastering Engineer", "known roles are translated: \(mastering?.title ?? "none")")
let combined = details.credits.first { $0.role == "Producer, Synthesizer" }?.title ?? ""
expect(combined.contains(", ") && combined != "Producer, Synthesizer", "combined roles translated part by part: \(combined)")

var video = SongDetails()
video.read(description: "The official video for \"Never Gonna Give You Up\".\n\nFollow Rick.")
expect(video.label == nil && video.credits.isEmpty, "an ordinary video has no catalogue data")
expect(video.description?.hasPrefix("The official video") == true, "and keeps its description")

print(failures == 0 ? "SongDetailsCheck: all checks passed" : "SongDetailsCheck: \(failures) failed")
exit(failures == 0 ? 0 : 1)
